"""ROM generator for golden_v2 (Praat-faithful, 638-sample window, subtractive octave cost).

Outputs in rom/:
  hanning638_q15.hex/.mif   638 x 16  unsigned Q1.15, w[j] = 0.5 - 0.5 cos(2 pi (j+1)/639), j = 0..637
  ck_rom.hex/.mif           256 x 32  (189 used, address = tau - 26, tau = 26..214)
                            bits[31:16] = C_q[tau]  unsigned Q2.14 = round(2^14 * Rw[0] / Rw[tau])
                            bits[15:0]  = K_q[tau]  signed, round(2^20 * 0.01 * log2(600 * tau / 16000))
  constants.vh              Verilog localparams (geometry, mean reciprocal, formats)
C uses the autocorrelation of the *quantised* window (the window the hardware really applies).
"""
import math
import os
import numpy as np
import constants as K


def hanning_q15():
    n = K.NSAMP_WINDOW
    w = [0.5 - 0.5 * math.cos(2 * math.pi * (j + 1) / (n + 1)) for j in range(n)]
    q = [min(32767, int(math.floor(v * 32768 + 0.5))) for v in w]
    for j in range(n):
        assert q[j] == q[n - 1 - j]
    return q


def c_table(wq=None):
    wq = np.array(wq if wq is not None else hanning_q15(), dtype=np.int64)
    rw = [int(np.dot(wq[: len(wq) - t], wq[t:])) for t in range(K.TAU_SCAN_MAX + 1)]
    return {t: int(math.floor((1 << K.C_FRAC) * rw[0] / rw[t] + 0.5)) for t in range(K.TAU_SCAN_MIN, K.TAU_SCAN_MAX + 1)}


def k_table():
    out = {}
    for t in range(K.TAU_SCAN_MIN, K.TAU_SCAN_MAX + 1):
        v = K.OCTAVE_COST * math.log2(K.PITCH_CEILING * t / K.FS)
        out[t] = int(math.floor(v * (1 << K.K_FRAC) + 0.5))
    return out


def write_hex_mif(name, words, width, depth=None):
    depth = depth or len(words)
    words = list(words) + [0] * (depth - len(words))
    nd = (width + 3) // 4
    mask = (1 << width) - 1
    with open(f'rom/{name}.hex', 'w') as f:
        for wv in words:
            f.write(f'{wv & mask:0{nd}X}\n')
    with open(f'rom/{name}.mif', 'w') as f:
        f.write(f'-- generated by golden_v2/gen_roms.py\nWIDTH={width};\nDEPTH={depth};\n'
                'ADDRESS_RADIX=UNS;\nDATA_RADIX=HEX;\nCONTENT BEGIN\n')
        for a, wv in enumerate(words):
            f.write(f'  {a} : {wv & mask:0{nd}X};\n')
        f.write('END;\n')


def main():
    os.makedirs('rom', exist_ok=True)
    w = hanning_q15()
    C, Kt = c_table(w), k_table()
    write_hex_mif('hanning638_q15', w, 16)
    packed = [((C[t] & 0xFFFF) << 16) | (Kt[t] & 0xFFFF) for t in range(K.TAU_SCAN_MIN, K.TAU_SCAN_MAX + 1)]
    write_hex_mif('ck_rom', packed, 32, depth=256)
    with open('rom/constants.vh', 'w') as f:
        f.write('// generated by golden_v2/gen_roms.py -- Praat 7.0.03 raw-ac geometry @ 16 kHz\n')
        for k, v in [('NSAMP_WINDOW', K.NSAMP_WINDOW), ('HALFNSAMP_WINDOW', K.HALFNSAMP_WINDOW),
                     ('MEAN_OFFSET', K.MEAN_OFFSET), ('MEAN_SPAN', K.MEAN_SPAN),
                     ('LP_FIRST', K.LP_FIRST), ('LP_LAST', K.LP_LAST),
                     ('TAU_SCAN_MIN', K.TAU_SCAN_MIN), ('TAU_SCAN_MAX', K.TAU_SCAN_MAX),
                     ('TAU_SEARCH_MIN', K.TAU_SEARCH_MIN), ('TAU_SEARCH_MAX', K.TAU_SEARCH_MAX),
                     ('W_FRAC', K.W_FRAC), ('C_FRAC', K.C_FRAC), ('K_FRAC', K.K_FRAC),
                     ('M_MEAN', K.M_MEAN), ('K_MEAN', K.K_MEAN), ('MEAN_BIAS', K.MEAN_BIAS)]:
            f.write(f'localparam integer {k} = {v};\n')
    print('hanning: w[0]=%d w[318]=%d w[319]=%d w[637]=%d sum=%d' % (w[0], w[318], w[319], w[637], sum(w)))
    print('C[26]=%d C[27]=%d C[100]=%d C[213]=%d C[214]=%d  max=%d' % (C[26], C[27], C[100], C[213], C[214], max(C.values())))
    print('K[26]=%d K[27]=%d K[100]=%d K[213]=%d K[214]=%d' % (Kt[26], Kt[27], Kt[100], Kt[213], Kt[214]))


if __name__ == '__main__':
    main()
