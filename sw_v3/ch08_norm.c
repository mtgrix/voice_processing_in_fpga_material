static uint8_t get_bitlen(uint64_t val) {
    uint8_t len = 0;
    while (val > 0) {
        len++;
        val >>= 1;
    }
    return len;
}

void ch08_norm_score(int64_t r0, const int64_t R[CH08_TAU_MAX + 1], ch08_norm_result_t *res) {
    if (r0 <= 0) {
        res->sh = 0;
        res->r0n = 0;
        for (int t = 0; t <= CH08_TAU_MAX; ++t) {
            res->U[t] = 0;
            res->Sc[t] = 0;
        }
        return;
    }

    uint8_t r0_len = get_bitlen((uint64_t)r0);
    uint8_t sh = (r0_len > 26) ? (r0_len - 26) : 0;
    uint32_t r0n = (uint32_t)(r0 >> sh);

    res->sh = sh;
    res->r0n = r0n;

    for (int t = 0; t < CH08_TAU_MIN; ++t) {
        res->U[t] = 0;
        res->Sc[t] = 0;
    }

    for (int t = CH08_TAU_MIN; t <= CH08_TAU_MAX; ++t) {
        int64_t rn = R[t] >> sh; // arithmetic right shift
        uint16_t c_coeff = ROM_C[t - CH08_TAU_MIN];
        int16_t  k_coeff = ROM_K[t - CH08_TAU_MIN];

        // U[tau] = (Rn * C[tau] + 2^13) >> 14
        int64_t prod_c = rn * (int64_t)c_coeff;
        int32_t u_div = (int32_t)((prod_c + 8192) >> 14);

        // term_k = (R0n * K[tau] + 2^19) >> 20
        int64_t prod_k = (int64_t)r0n * (int64_t)k_coeff;
        int32_t term_k = (int32_t)((prod_k + 524288) >> 20);

        int32_t sc_diff = u_div - term_k;

        res->U[t] = u_div;
        res->Sc[t] = sc_diff;
    }
}
